const BASE_TIME = Date.UTC(2026, 0, 5, 9, 0, 0);
const DAY = 24 * 3600_000;

function demoSha(title: string): string {
  return createHash('sha1').update(`demo:${title}`).digest('hex');
}

/** Split PR churn across files deterministically (for per-file fingerprints). */
function fileChurn(s: Scenario) {
  const n = s.files.length;
  return s.files.map((filename, i) => ({
    filename,
    status: 'modified',
    additions: Math.floor(s.additions / n) + (i < s.additions % n ? 1 : 0),
    deletions: Math.floor(s.deletions / n) + (i < s.deletions % n ? 1 : 0),
  }));
}

export async function seedDemoData(prisma: PrismaClient): Promise<{ repositories: number; pull_requests: number; new_scores: number }> {
  const repos = [];
  for (const r of DEMO_REPOS) {
    const data = {
      full_name: `${r.owner}/${r.name}`,
      owner: r.owner,
      name: r.name,
      installation_id: 0n,
      private: false,
      visibility: 'public',
      is_demo: true,
      access_status: 'active',
      access_revoked_at: null,
    };
    repos.push(await prisma.repo.upsert({ where: { github_repo_id: r.github_repo_id }, update: data, create: { github_repo_id: r.github_repo_id, ...data } }));
  }

  let newScores = 0;
  for (const [i, s] of DEMO_SCENARIOS.entries()) {
    const repo = repos[i % repos.length];
    const number = i + 1;
    const headSha = demoSha(s.title);
    const createdAt = new Date(BASE_TIME + i * DAY);
    const updatedAt = new Date(BASE_TIME + i * DAY + 6 * 3600_000);
    const closedAt = s.state === 'closed' ? new Date(BASE_TIME + i * DAY + 8 * 3600_000) : null;
    const prData = {
      title: s.title,
      state: s.state,
      draft: false,
      author: s.author,
      head_sha: headSha,
      base_ref: s.base_ref,
      head_ref: s.head_ref,
      additions: s.additions,
      deletions: s.deletions,
      changed_files: s.changed_files,
      changed_files_list: s.files,
      identity_status: 'verified',
      github_created_at: createdAt,
      github_updated_at: updatedAt,
      closed_at: closedAt,
      merged_at: s.merged ? closedAt : null,
    };
    const pr = await prisma.pullRequest.upsert({
      where: { repo_id_number: { repo_id: repo.id, number } },
      update: prData,
      create: { repo_id: repo.id, number, ...prData },
    });

    const files = fileChurn(s);
    const coverage = { expected_files: s.changed_files, listed_files: s.files.length, complete: s.files.length >= s.changed_files };
    const scoring = computeScore({
      changed_files: s.changed_files,
      additions: s.additions,
      deletions: s.deletions,
      changed_files_list: s.files,
      ci_status: s.ci,
      ci_reason: s.ci_reason,
      coverage,
    });
    const fingerprint = runFingerprint({
      scoringVersion: SCORING_VERSION,
      headSha,
      baseRef: s.base_ref,
      changedFiles: s.changed_files,
      additions: s.additions,
      deletions: s.deletions,
      files,
      fileListComplete: coverage.complete,
      ciStatus: s.ci,
    });

    const existing = await prisma.analysisRun.findUnique({
      where: { pull_request_id_input_fingerprint: { pull_request_id: pr.id, input_fingerprint: fingerprint } },
    });
    if (existing) continue;

    const json = (v: unknown) => JSON.parse(stableStringify(v)) as Prisma.InputJsonValue;
    await prisma.$transaction(async (tx) => {
      const run = await tx.analysisRun.create({
        data: {
          pull_request_id: pr.id,
          head_sha: headSha,
          input_fingerprint: fingerprint,
          scoring_version: SCORING_VERSION,
          ci_status: s.ci,
          ai_status: s.aiFixture ? 'succeeded' : 'disabled',
          comment_status: 'disabled',
          completed_at: updatedAt,
          created_at: updatedAt,
        },
      });
      await tx.prScore.create({
        data: {
          pull_request_id: pr.id,
          run_id: run.id,
          score: scoring.score,
          level: levelToApi(scoring.level),
          reasons: scoring.reasons,
          features: json(scoring.features),
          contributions: json(scoring.contributions),
          coverage: json({ ...coverage, files_without_patch: 0, reason: coverage.complete ? null : 'demo file list is abbreviated', uncertainties: scoring.uncertainties }),
          head_sha: headSha,
          scoring_version: SCORING_VERSION,
          ci_status: s.ci,
          input_fingerprint: fingerprint,
          created_at: updatedAt,
        },
      });
      if (s.aiFixture) {
        await tx.prAiAnalysis.create({
          data: {
            pull_request_id: pr.id,
            run_id: run.id,
            analysis_json: json(s.aiFixture),
            model: 'demo-fixture',
            prompt_version: 'demo',
            head_sha: headSha,
            input_fingerprint: `demo:${fingerprint}`,
            limitations: json({ note: 'Static demo fixture; no model was called.' }),
            created_at: updatedAt,
          },
        });
      }
    });
    newScores += 1;
  }

  return { repositories: repos.length, pull_requests: DEMO_SCENARIOS.length, new_scores: newScores };
}
