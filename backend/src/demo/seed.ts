/**
 * Deterministic, repeatable demo data (the single seed path for the DB).
 *
 *  - Demo repositories use reserved negative github_repo_id values and
 *    is_demo=true, so they can never collide with real GitHub identities.
 *  - SHAs and timestamps are derived from the scenario, never random.
 *  - Scores come from the real scoring engine and are keyed by the same run
 *    fingerprint the worker uses, so re-running creates no duplicate history.
 *  - The two AI analyses are labelled fixtures (model "demo-fixture"), not
 *    output from a model.
 */

